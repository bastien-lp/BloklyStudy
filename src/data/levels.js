// Définition de niveau correspondant à un total d'XP.
export function levelFromXp(xp = 0) {
  return [...XP_LEVELS].reverse().find(l => xp >= l.xpNeeded) || XP_LEVELS[0];
}

// XP cumulé requis pour atteindre un niveau donné.
export function xpForLevel(lvl) {
  const i = Math.max(1, Math.min(XP_LEVELS.length, lvl || 1)) - 1;
  return XP_LEVELS[i].xpNeeded;
}
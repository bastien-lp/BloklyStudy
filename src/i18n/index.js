/* ════════════════════════════ ENGINE ══════════════════════════════════ */

/** Resolve a dotted key ("journal.newEntry") inside a nested dictionary. */
function resolve(dict, key) {
  if (!dict) return undefined;
  return key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), dict);
}

/** Replace {tokens} in a template. `count` is localized as a number. */
function interpolate(template, options, lang) {
  return template.replace(/\{(\w+)\}/g, (_, token) => {
    if (token === 'count' && typeof options.count === 'number') {
      return new Intl.NumberFormat(lang).format(options.count);
    }
    const value = options[token];
    return value == null ? '' : String(value);
  });
}

/**
 * Translate a key for `lang`, falling back to French then to the raw key.
 * With `options.count`, picks the plural form via Intl.PluralRules.
 */
function translate(lang, key, options = {}) {
  const candidates = [];
  if (typeof options.count === 'number') {
    const cat = new Intl.PluralRules(lang).select(options.count);
    const fallbackCat = new Intl.PluralRules(DEFAULT_LANG).select(options.count);
    candidates.push(`${key}_${cat}`, `${key}_${fallbackCat}`, `${key}_other`);
  }
  candidates.push(key);

  for (const candidate of candidates) {
    const template = resolve(LOCALES[lang], candidate) ?? resolve(LOCALES[DEFAULT_LANG], candidate);
    if (typeof template === 'string') return interpolate(template, options, lang);
  }
  return key; // last resort: surface the key so gaps are visible in dev
}

/* ════════════════════════════ REACT API ═══════════════════════════════ */

const I18nContext = createContext(null);

/**
 * Wraps the app and exposes translation helpers via context.
 * `lang` comes from user prefs (persisted like the theme). Unknown/undefined
 * languages fall back to French.
 */
export function LanguageProvider({ lang = DEFAULT_LANG, children }) {
  const value = useMemo(() => {
    const active = LOCALES[lang] ? lang : DEFAULT_LANG;
    return {
      lang: active,
      t: (key, options) => translate(active, key, options),
      formatDate: (v, opts) => new Intl.DateTimeFormat(active, opts).format(v instanceof Date ? v : new Date(v)),
      formatNumber: (n, opts) => new Intl.NumberFormat(active, opts).format(n),
    };
  }, [lang]);

  // createElement (no JSX) so this stays a plain .js file.
  return createElement(I18nContext.Provider, { value }, children);
}

/** Hook used by every component that displays text. */
export function useTranslation() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useTranslation() must be used inside <LanguageProvider>.');
  return ctx;
}